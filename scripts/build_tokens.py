"""Build market_update/static/tokens.css from tokens.json (DTCG).

tokens.json is the one source of truth for colour. This writes one CSS-variable layer:
  --p-<group>-<step>   primitives, the palette (components never name these)
  --<group>-<name>     semantic tokens, what a colour is for
  legacy aliases       the variable names the stylesheet already uses (--canvas, --up, ...),
                       pointed at the semantic layer so old rules follow the theme
Run:  python3 scripts/build_tokens.py
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent / "market_update" / "static"
SRC, OUT = ROOT / "tokens.json", ROOT / "tokens.css"

# old name -> semantic token. Kept so the 4,000-line stylesheet keeps working while it migrates.
LEGACY = {
    "canvas": "surface-canvas", "bg": "surface-canvas", "surface": "surface-plate", "surface-2": "surface-raised",
    "topbar": "surface-topbar", "nav-hover": "surface-hover",
    "line": "line-default", "line-2": "line-strong", "input-border": "line-input", "border": "line-default", "border-2": "line-strong",
    "text": "text-primary", "text-2": "text-secondary", "muted": "text-muted", "nav-text": "text-nav",
    "brand": "action-primary", "brand-hover": "action-primary-hover", "brand-ink": "action-primary-ink",
    "brand-text": "action-accent-text", "brand-tint": "action-accent-tint", "accent": "action-accent-text",
    "accent-ink": "action-primary-ink", "hi-bg": "action-accent-tint",
    "up": "market-up", "green": "market-up", "down": "market-down", "red": "market-down",
    "warn": "market-warn", "flat": "market-flat",
    "s1": "action-accent-text", "s2": "market-warn", "s3": "market-flat",
    "pill-ok": "market-up", "pill-ok-bg": "market-up-tint", "pill-warn": "market-warn", "pill-warn-bg": "market-warn-tint",
    "pill-bad": "market-down", "pill-bad-bg": "market-down-tint", "pill-acc": "action-accent-text", "pill-acc-bg": "action-accent-tint",
}


def walk(node, path):
    """Yield (path, value) for every leaf token."""
    for k, v in node.items():
        if k.startswith("$"):
            continue
        if isinstance(v, dict) and "$value" in v:
            yield path + [k], v["$value"]
        elif isinstance(v, dict):
            yield from walk(v, path + [k])


def main():
    data = json.loads(SRC.read_text())
    prim = {tuple(p): v for p, v in walk(data["primitive"], [])}
    lines = ["/* GENERATED by scripts/build_tokens.py from tokens.json. Do not edit by hand. */", ":root {", "  color-scheme: dark;"]
    for p, v in prim.items():
        if not re.fullmatch(r"#[0-9A-Fa-f]{6}", v):
            sys.exit(f"primitive {'.'.join(p)} is not a 6-digit hex: {v}")
        lines.append(f"  --p-{'-'.join(p)}: {v.upper()};")
    sem = {}
    for p, v in walk(data["semantic"], []):
        m = re.fullmatch(r"\{primitive\.([\w.-]+)\}", v)
        if not m or tuple(m.group(1).split(".")) not in prim:
            sys.exit(f"semantic {'.'.join(p)} must alias a primitive, got {v}")
        name = "-".join(p)
        sem[name] = True
        lines.append(f"  --{name}: var(--p-{m.group(1).replace('.', '-')});")
    for old, new in LEGACY.items():
        if new not in sem:
            sys.exit(f"legacy alias {old} points at unknown token {new}")
        lines.append(f"  --{old}: var(--{new});")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT.parent.parent)}: {len(prim)} primitives, {len(sem)} semantic, {len(LEGACY)} aliases")


if __name__ == "__main__":
    main()
